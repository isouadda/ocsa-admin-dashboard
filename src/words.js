// The language the screen is being drawn in. The app sets it before anything renders and again on
// every change, the way it sets the theme, so tr() reads one value rather than taking one.
let current = "en";
export function setLang(id) { current = LOCALES.indexOf(id) >= 0 ? id : "en"; }
export function getLang() { return current; }
export function localeTag(lang) { return LOCALE_TAGS[lang || current] || LOCALE_TAGS.en; }

// What a browser says it wants, when nothing is stored.
export function browserLang() {
  try {
    const want = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]) || [];
    for (let i = 0; i < want.length; i += 1) {
      const two = String(want[i] || "").slice(0, 2).toLowerCase();
      if (LOCALES.indexOf(two) >= 0) return two;
    }
  } catch (e) { /* a browser that will not say is an English one */ }
  return "en";
}

const fill = (text, values) => String(text).replace(/\{(\d+)\}/g, (m, i) => {
  const v = values[Number(i)];
  return v === undefined || v === null ? "" : String(v);
});
// The text before the bar, which is the English a key falls back to.
const baseOf = (key) => { const i = String(key).lastIndexOf("|"); return i > 0 ? String(key).slice(0, i) : String(key); };

export function tr(key, ...values) {
  const entry = WORDS[key];
  const said = entry && typeof entry[current] === "string" && entry[current] !== "" ? entry[current] : null;
  return fill(said === null ? baseOf(key) : said, values);
}

const RULES = {};
function rulesFor(lang) {
  if (!RULES[lang]) {
    try { RULES[lang] = new Intl.PluralRules(localeTag(lang)); }
    catch (e) { RULES[lang] = { select: (n) => (Number(n) === 1 ? "one" : "other") }; }
  }
  return RULES[lang];
}

// A count and its word, in whichever form the language uses for that number. {0} is the count.
export function trn(key, count, ...values) {
  const entry = WORDS[key] || {};
  const pick = (forms, lang) => {
    if (!forms || typeof forms !== "object") return null;
    const form = rulesFor(lang).select(Number(count));
    return forms[form] !== undefined ? forms[form] : (forms.other !== undefined ? forms.other : null);
  };
  const said = pick(entry[current], current);
  const english = said === null ? pick(entry.en, "en") : said;
  return fill(english === null ? baseOf(key) : english, [count].concat(values));
}
